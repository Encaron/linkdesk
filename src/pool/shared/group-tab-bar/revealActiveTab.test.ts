/**
 * revealActiveTab 单测——04 池「标签栏内容自适应与横向滚动」配套判据。
 *
 * 纯函数：给定滚动容器状态与目标标签位置，增量必须恰好把目标完整带进视野——
 * 已可见 ⇒ 0（不许多余滚动把用户手滚的位置拽走）；露出多少补多少（不许滚过头）。
 * 数值全虚构（硬约束 21 不适用——无文案无插件名，纯几何）。
 */

import { describe, it, expect } from "vitest";
import { revealDelta } from "./revealActiveTab";

describe("revealDelta——已在视野内", () => {
  it("完全可见 ⇒ 0（不拽动用户手滚过的位置）", () => {
    expect(revealDelta(100, 800, 300, 120)).toBe(0);
  });

  it("左缘贴住可视区左界 ⇒ 0", () => {
    expect(revealDelta(100, 800, 100, 120)).toBe(0);
  });

  it("右缘贴住可视区右界 ⇒ 0", () => {
    // 可视区 = [100, 900)；标签 [780, 900) 恰好收进
    expect(revealDelta(100, 800, 780, 120)).toBe(0);
  });
});

describe("revealDelta——右溢出", () => {
  it("完全在右 ⇒ 最小增量把整只带进来（不多滚——标签左缘不必贴左界）", () => {
    // 可视区 [0,800)，标签 [1200,1320) ⇒ 右溢 520，滚 520 后标签右缘贴可视区右界
    expect(revealDelta(0, 800, 1200, 120)).toBe(520);
  });

  it("部分露出（右半截被裁）⇒ 只补露出的量", () => {
    // 可视区 [0,800)，标签 [750, 900) ⇒ 露出 100
    expect(revealDelta(0, 800, 750, 150)).toBe(100);
  });
});

describe("revealDelta——左溢出", () => {
  it("完全在左 ⇒ 负增量滚到标签左缘", () => {
    // scrollLeft=500，标签在内容坐标 [100, 220) ⇒ 往左滚 400
    expect(revealDelta(500, 800, 100, 120)).toBe(-400);
  });

  it("部分被裁（左半截）⇒ 只补露出的量", () => {
    // scrollLeft=120，标签 [100, 260) ⇒ 左裁 20
    expect(revealDelta(120, 800, 100, 160)).toBe(-20);
  });
});

describe("revealDelta——边界", () => {
  it("标签比可视区还宽 ⇒ 对齐左缘（标题开头优先，右端交给用户继续滚）", () => {
    // 可视区 300，标签宽 500 在 [1000, 1500) ⇒ 滚 1000，标签左缘对齐可视区左界
    expect(revealDelta(0, 300, 1000, 500)).toBe(1000);
  });
});
