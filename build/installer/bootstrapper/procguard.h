// 【规格】05-实现交接.md §4.3：「优雅关闭：枚举顶层窗口发 WM_CLOSE（**禁止 taskkill 硬杀**），
//   10s 超时回「稍后」」；02-流程设计.md §三「已有实例在跑 → 询问关闭（关闭并继续 / 稍后），
//   不静默杀进程」。
//
// 【为什么另开一个文件】`syswrite.{h,cpp}` 是「**往系统里写什么**」的清单（键逐条照抄
//   `build/installer.nsh`）；本文件是「**怎么跟已经在跑的 LinkDesk 打交道**」——读进程、
//   发窗口消息，一个字节都不往系统写。两件事的真相源不同（一个是 nsh、一个是 §4.3 的行为
//   口径），混在一处会让 2d 移植卸载清理清单时分不清「哪些是照抄的键」与「哪些是新规矩」。
//
// 【为什么不做成阻塞式「发完 WM_CLOSE 就地等 10 秒」】本模块被 UI 线程的 WebMessage 回调调用；
//   在里面 Sleep 十秒会让窗口僵死（Windows 会画「未响应」），而若就地跑消息泵又会让
//   WebView2 的消息回调**重入**。⇒ 这里只「发请求 + 即时探测」；**等待与超时由宿主的定时器
//   （main.cpp 的 kCloseWaitTimer）驱动**，UI 全程活着。
// ══════════════════════════════════════════════════════════════════════════

#ifndef LINKDESK_PROCGUARD_H
#define LINKDESK_PROCGUARD_H

#include <windows.h>

/** 进程镜像名（不含路径，大小写不敏感）。改名/换壳要同笔改这里与 04 §对账表。 */
extern const wchar_t* kAppProcessName;   // "LinkDesk.exe"

/** LinkDesk 在不在跑——按**进程镜像名**认，不认窗口标题。
 *  窗口标题是用户可见文案（随语言/版本变），进程名才是安装契约；且这样也覆盖
 *  「有窗口的」与「只有后台进程、没有顶层窗」两类。 */
bool IsAppRunning();

/** 给 LinkDesk 的每个顶层窗口 PostMessage(WM_CLOSE)，返回发出的窗口数。
 *  ⚠️ **不是** TerminateProcess：关闭动作走软件自身的退出流程（保存工作区等），
 *  这与「禁 taskkill」是同一条规矩。返回 0 = 根本没找到窗口（后台进程 / 已退出）。 */
int RequestAppClose();

#endif  // LINKDESK_PROCGUARD_H
